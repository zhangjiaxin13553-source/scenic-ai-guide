# ===================== 对外调用函数 =====================
def get_fallback_response(fault_type: FaultType, role: RoleType) -> str:
    """
    根据故障类型+角色口吻，随机返回一条兜底话术
    :param fault_type: 故障类型 timeout/api_error/circuit_break/low_quality
    :param role: 角色 luxun=鲁迅数字人 / guide=讲解员
    :return: 对应风格兜底文本
    """
    sentence_list = FALLBACK_DICT[fault_type][role]
    return random.choice(sentence_list)